"""
AI Query Agent — DIAL-backed assistant for migration validation.

Responsibilities
----------------
1. Read rules_catalog.json to know what rules exist and when to apply them.
2. Accept schema metadata (source + target column lists) from the caller.
3. Build a carefully structured prompt and call the DIAL API
   (OpenAI-compatible endpoint) to get rule assignments + SQL queries.
4. Parse the JSON response into ColumnMapping objects the rest of the
   framework can consume directly.
5. Graceful fallback: if DIAL_API_KEY is not set, apply rules using the
   static rule-matching logic already in transformation_rules.py.

Environment variables
---------------------
DIAL_API_KEY      — required for AI mode
DIAL_API_BASE     — defaults to https://ai-proxy.lab.epam.com  (EPAM VPN required)
DIAL_API_VERSION  — Azure OpenAI api-version, defaults to 2025-04-01-preview
DIAL_MODEL        — deployment name, defaults to gpt-4o

Usage (programmatic)
--------------------
    from ai_query_agent import AIQueryAgent
    from models import DatabaseType

    agent = AIQueryAgent()
    result = agent.generate_validation_plan(
        source_db_type=DatabaseType.POSTGRESQL,
        source_schema="source_data",
        source_table="users",
        source_columns=[{"column_name": "user_id", "data_type": "SERIAL", ...}, ...],
        target_db_type=DatabaseType.SNOWFLAKE,
        target_schema="target_schema",
        target_table="USERS",
        target_columns=[{"column_name": "USER_ID", "data_type": "NUMBER", ...}, ...],
        target_database="snowflake_db",
    )
    # result.source_sql  — ready to run on source DB
    # result.target_sql  — ready to run on target DB (Snowflake)
    # result.column_mappings  — list of ColumnMapping dataclass instances
    # result.rules_applied  — dict of col -> [rule_ids]
    # result.explanation  — human-readable reasoning from the AI
"""

