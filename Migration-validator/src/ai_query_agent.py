@dataclass
class ValidationPlan:
    """Everything the AI agent produces for a single source→target table pair."""
    source_db_type: DatabaseType
    target_db_type: DatabaseType
    source_schema: str
    source_table: str
    target_schema: str
    target_table: str
    target_database: Optional[str]

    column_mappings: List[ColumnMapping] = field(default_factory=list)
    rules_applied: Dict[str, List[str]] = field(default_factory=dict)
    source_sql: str = ""
    target_sql: str = ""
    explanation: str = ""
    generated_by: str = "static"  # "ai" | "static"

    def print_summary(self):
        """Pretty-print plan to stdout."""
        sep = "=" * 70
        print(f"\n{sep}")
        print(f"  VALIDATION PLAN  |  {self.source_table} → {self.target_table}")
        print(sep)
        print(f"  Generated by : {self.generated_by.upper()}")
        print(f"  Source       : {self.source_db_type.value}.{self.source_schema}.{self.source_table}")
        tf = f"{self.target_database + '.' if self.target_database else ''}{self.target_schema}.{self.target_table}"
        print(f"  Target       : {self.target_db_type.value}.{tf}")
        print(f"\n  Column mappings ({len(self.column_mappings)}):")
        for cm in self.column_mappings:
            rules = ", ".join(r.value for r in cm.apply_rules) or "none"
            pk = " [PK]" if cm.primary_key else ""
            print(f"    {cm.source_column}({cm.source_data_type}){pk} -> {cm.target_column}({cm.target_data_type})  rules: [{rules}]")
        if self.explanation:
            print(f"\n  AI reasoning:\n    {self.explanation[:400]}")
        print(f"\n{'─' * 70}")
        print("  SOURCE SQL:")
        print(f"{'─' * 70}")
        print(self.source_sql)
        print(f"\n{'─' * 70}")
        print("  TARGET SQL:")
        print(f"{'─' * 70}")
        print(self.target_sql)
        print(sep)


