class RulesCatalog:
    """Thin wrapper around rules_catalog.json."""

    def __init__(self, path: Path = _CATALOG_PATH):
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
        self._rules: List[Dict[str, Any]] = data["rules"]
        self._chain_order: List[str] = data.get("chaining_order", [])
        # Build lookup: enum_value -> rule dict
        self._by_enum: Dict[str, Dict[str, Any]] = {r["enum_value"]: r for r in self._rules}

    def all_rules(self) -> List[Dict[str, Any]]:
        return self._rules

    def prompt_summary(self) -> str:
        """Compact representation of all rules to inject into the system prompt."""
        lines = []
        for r in self._rules:
            triggers = ", ".join(
                f"{p['source']}→{p['target']}" for p in r["trigger_type_pairs"]
            )
            lines.append(
                f"- {r['enum_value']}: {r['description']}  "
                f"[auto_detect={r['auto_detect']}]  triggers on: {triggers}"
            )
        return "\n".join(lines)

    def enum_value_to_rule_type(self, enum_value: str) -> Optional[TransformationRuleType]:
        try:
            return TransformationRuleType(enum_value.lower())
        except ValueError:
            return None

    def chain_order(self) -> List[str]:
        return self._chain_order


_catalog = RulesCatalog()


# ---------------------------------------------------------------------------
# Static fallback rule-matching (no AI required)
# ---------------------------------------------------------------------------

def _static_rule_match(source_type: str, target_type: str) -> List[TransformationRuleType]:
    """
    Apply the catalog's auto_detect logic to pick rules for a type pair.
    Returns a list of TransformationRuleType values in chaining order.
    """
    matched: List[TransformationRuleType] = []
    src_up = source_type.upper()
    tgt_up = target_type.upper()

    # Strip width/precision modifiers for matching: VARCHAR(100) -> VARCHAR
    src_base = re.sub(r"\(.*\)", "", src_up).strip()
    tgt_base = re.sub(r"\(.*\)", "", tgt_up).strip()

    for rule_def in _catalog.all_rules():
        if not rule_def.get("auto_detect"):
            continue
        for pair in rule_def["trigger_type_pairs"]:
            s, t = pair["source"].upper(), pair["target"].upper()
            # Wildcard pair ("*") matches everything
            if s == "*" or t == "*":
                rt = _catalog.enum_value_to_rule_type(rule_def["enum_value"])
                if rt and rt not in matched:
                    matched.append(rt)
                break
            if src_base.startswith(s) and tgt_base.startswith(t):
                rt = _catalog.enum_value_to_rule_type(rule_def["enum_value"])
                if rt and rt not in matched:
                    matched.append(rt)
                break

    # Sort by chain order
    chain = _catalog.chain_order()
    matched.sort(key=lambda r: chain.index(r.value) if r.value in chain else len(chain))
    return matched


# ---------------------------------------------------------------------------
# Column matcher (by name, case-insensitive)
# ---------------------------------------------------------------------------

def _match_columns(
    source_cols: List[Dict[str, Any]],
    target_cols: List[Dict[str, Any]],
) -> List[Dict[str, Any]]:
    """
    Pair source and target columns by normalised name.
    Returns list of {"source": col_dict, "target": col_dict} pairs.
    Unmatched columns are logged but not included.
    """
    tgt_by_name = {c["column_name"].upper(): c for c in target_cols}
    pairs = []
    for sc in source_cols:
        key = sc["column_name"].upper()
        tc = tgt_by_name.get(key)
        if tc:
            pairs.append({"source": sc, "target": tc})
        else:
            print(f"  [WARN] No target column found for source '{sc['column_name']}' — skipped", file=sys.stderr)
    return pairs


