def _parse_ai_response(raw_json: str, pairs: List[Dict]):
    """Parse AI JSON response into ColumnMapping list."""
    import json as _json
    try:
        data = _json.loads(raw_json)
    except Exception as exc:
        print(f"  [WARN] Could not parse AI response: {exc}")
        return QueryBuilder._static_mappings(pairs, [])

    mappings = []
    active_count = 0
    skipped_count = 0

    for cm in data.get("column_mappings", []):
        rules = []
        ignore = cm.get("ignore_validation", False)

        if not ignore:
            for rule_str in cm.get("apply_rules", []):
                rt = _enum_val_to_rule_type(rule_str)
                if rt:
                    rules.append(rt)
                else:
                    print(f"  [WARN] Unknown rule '{rule_str}' for column "
                          f"'{cm.get('source_column', '?')}' — ignored.")

        mapping = ColumnMapping(
            source_column=cm["source_column"],
            target_column=cm["target_column"],
            source_data_type=cm.get("source_data_type", ""),
            target_data_type=cm.get("target_data_type", ""),
            apply_rules=rules,
            primary_key=cm.get("primary_key", False),
            ignore_validation=ignore,
        )
        mappings.append(mapping)

        if ignore:
            skipped_count += 1
        else:
            active_count += 1

    print(f"  [AI] Parsed {len(mappings)} column mappings: "
          f"{active_count} active, {skipped_count} skipped (complex types)")

    explanation = data.get("explanation", "")
    return mappings, explanation, "ai"


