def _auto_detect_pks(columns: List[ColumnInfo]) -> List[str]:
    for col in columns:
        name = col.column_name.lower()
        if name in ("id",) or name.endswith("_id"):
            if any(t in col.data_type.upper() for t in ("INT", "SERIAL", "NUMBER", "BIGINT")):
                return [col.column_name]
    return []


def _enum_val_to_rule_type(enum_value: str) -> Optional[TransformationRuleType]:
    """
    Convert a rule string from AI response to TransformationRuleType.
    AI may return UPPER_CASE, lower_case, or mixed — handle all cases.

    TransformationRuleType enum values are stored in lower_case
    (e.g. 'null_standardization'), but the AI often returns UPPER_CASE
    (e.g. 'NULL_STANDARDIZATION'). Both must resolve correctly.
    """
    if not enum_value:
        return None
    # Try exact lower-case match first (canonical form)
    try:
        return TransformationRuleType(enum_value.lower())
    except ValueError:
        pass
    # Try upper-case value match (AI sometimes returns the enum NAME not value)
    # e.g. AI says 'NULL_STANDARDIZATION' which is also the enum member name
    try:
        return TransformationRuleType[enum_value.upper()]
    except KeyError:
        pass
    # Last resort: scan all members for a case-insensitive match
    search = enum_value.lower().strip()
    for member in TransformationRuleType:
        if member.value.lower() == search or member.name.lower() == search:
            return member
    return None
