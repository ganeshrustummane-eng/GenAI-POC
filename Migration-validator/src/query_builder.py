@dataclass
class QueryResult:
    """All queries generated for one source→target table pair."""
    table_name: str
    source_db: str
    target_db: str
    generated_by: str = "static"     # "ai" | "static"
    ai_explanation: str = ""

    # ── Primary validation queries ──────────────────────────────────────────
    source_sql: str = ""             # Run on PostgreSQL
    target_sql: str = ""             # Run on Snowflake

    # ── Supporting completeness queries ─────────────────────────────────────
    row_count_source_sql: str = ""   # COUNT(*) on source
    row_count_target_sql: str = ""   # COUNT(*) on target
    null_check_source_sql: str = ""  # NULL % per column — source
    null_check_target_sql: str = ""  # NULL % per column — target
    duplicate_pk_sql: str = ""       # Duplicate PK check on target
    missing_rows_sql: str = ""       # Rows in source missing from target

    column_mappings: List[ColumnMapping] = field(default_factory=list)
    skipped_columns: List[str] = field(default_factory=list)
    timestamp: str = field(default_factory=lambda: datetime.now().isoformat())

    def print_queries(self):
        """Pretty-print all queries to stdout."""
        sep = "=" * 70
        thin = "─" * 70

        print(f"\n{sep}")
        print(f"  📋 VALIDATION QUERIES  |  {self.table_name}")
        print(f"  Generated by : {self.generated_by.upper()}")
        print(f"  Source DB    : {self.source_db}")
        print(f"  Target DB    : {self.target_db}")
        print(sep)

        if self.ai_explanation:
            print(f"\n  💡 AI Reasoning:\n  {self.ai_explanation[:500]}")

        print(f"\n{thin}")
        print(f"  ① ROW COUNT — Run on PostgreSQL")
        print(thin)
        print(self.row_count_source_sql)

        print(f"\n{thin}")
        print(f"  ② ROW COUNT — Run on Snowflake")
        print(thin)
        print(self.row_count_target_sql)

        print(f"\n{thin}")
        print(f"  ③ MAIN VALIDATION QUERY — Run on PostgreSQL  (normalised data)")
        print(thin)
        if self.source_sql:
            print(self.source_sql)
        else:
            print("  -- ⚠ No source SQL generated.")
            print("  -- This means all column mappings were skipped (complex types)")
            print("  -- or the AI returned rule names that could not be resolved.")
            print(f"  -- Column mappings received: {len(self.column_mappings)}")
            print(f"  -- Skipped columns: {self.skipped_columns}")

        print(f"\n{thin}")
        print(f"  ④ MAIN VALIDATION QUERY — Run on Snowflake  (normalised data)")
        print(thin)
        if self.target_sql:
            print(self.target_sql)
        else:
            print("  -- ⚠ No target SQL generated.")
            print("  -- Check that active (non-skipped) column mappings exist.")

        if self.null_check_source_sql:
            print(f"\n{thin}")
            print(f"  ⑤ NULL % CHECK — Run on PostgreSQL")
            print(thin)
            print(self.null_check_source_sql)

        if self.null_check_target_sql:
            print(f"\n{thin}")
            print(f"  ⑥ NULL % CHECK — Run on Snowflake")
            print(thin)
            print(self.null_check_target_sql)

        if self.duplicate_pk_sql:
            print(f"\n{thin}")
            print(f"  ⑦ DUPLICATE PK CHECK — Run on Snowflake")
            print(thin)
            print(self.duplicate_pk_sql)

        if self.missing_rows_sql:
            print(f"\n{thin}")
            print(f"  ⑧ MISSING ROWS CHECK — Run on PostgreSQL")
            print(thin)
            print(self.missing_rows_sql)

        if self.skipped_columns:
            print(f"\n  ⚠️  Skipped columns (complex types — manual review needed):")
            for col in self.skipped_columns:
                print(f"       • {col}")

        print(f"\n{sep}")
        print(f"  ✅  Copy the queries above and run them in your SQL client.")
        print(f"  📊  Compare ③ vs ④ results to validate data completeness.")
        print(sep)


