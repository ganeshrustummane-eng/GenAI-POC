"""
Query Builder — AI-Powered SQL Query Generator (Output Only)
=============================================================
Takes database/schema/table as input.
Connects to PostgreSQL + Snowflake to extract REAL column metadata.
Sends everything to AI (GPT-4o via DIAL).
OUTPUT = Ready-to-run SQL queries for both source and target.

You copy those queries and run them yourself in your SQL client.
Nothing is executed here.

Flow
----
  1. Connect to PostgreSQL  → fetch column metadata
  2. Connect to Snowflake   → fetch column metadata
  3. Inject column metadata + full rule book into AI prompt
  4. AI returns: column mappings + rules to apply per column
  5. SQL generator builds the final normalised queries
  6. Queries printed to terminal + saved to validation_sql/

Usage (programmatic)
--------------------
  from query_builder import QueryBuilder

  builder = QueryBuilder()
  result = builder.build(
      pg_database="fms",
      pg_schema="public",
      pg_table="events",
      sf_schema="storedge_fms_public",
      sf_table="EVENTS",
      primary_keys=["event_id"],
  )
  # result.source_sql  ← run this on PostgreSQL
  # result.target_sql  ← run this on Snowflake
  # result.extra_queries  ← row count, null %, duplicate PK queries
"""

