def _build_source_sql(
    schema: str, table: str,
    mappings: List[ColumnMapping],
    pk_cols: List[str],
) -> str:
    """Build the normalised SELECT query for PostgreSQL."""
    select_parts = []
    for cm in mappings:
        if cm.apply_rules:
            expr = rules_engine.apply_rules(
                cm.source_column, cm.apply_rules,
                DatabaseType.POSTGRESQL,
                alias=f"{cm.source_column}_normalized",
            )
        else:
            expr = f"{cm.source_column} AS {cm.source_column}_normalized"
        select_parts.append(f"    {expr}")

    order_by = ", ".join(pk_cols) if pk_cols else "1"
    cols_sql = ",\n".join(select_parts)

    return (
        f"-- ── SOURCE: PostgreSQL ── {schema}.{table} ──────────────────────\n"
        f"SELECT\n{cols_sql}\nFROM {schema}.{table}\nORDER BY {order_by};"
    )


def _build_target_sql(
    database: str, schema: str, table: str,
    mappings: List[ColumnMapping],
    pk_cols: List[str],
) -> str:
    """Build the normalised SELECT query for Snowflake."""
    select_parts = []
    for cm in mappings:
        if cm.apply_rules:
            expr = rules_engine.apply_rules(
                cm.target_column, cm.apply_rules,
                DatabaseType.SNOWFLAKE,
                alias=f"{cm.source_column}_normalized",  # same alias as source for comparison
            )
        else:
            expr = f"{cm.target_column} AS {cm.source_column}_normalized"
        select_parts.append(f"    {expr}")

    order_by = ", ".join(pk_cols) if pk_cols else "1"
    cols_sql = ",\n".join(select_parts)
    full_table = f"{database}.{schema}.{table}" if database else f"{schema}.{table}"

    return (
        f"-- ── TARGET: Snowflake ── {full_table} ──────────────────────────\n"
        f"SELECT\n{cols_sql}\nFROM {full_table}\nORDER BY {order_by};"
    )


def _row_count_sql_pg(schema: str, table: str) -> str:
    return (
        f"-- ── ROW COUNT: PostgreSQL ───────────────────────────────────────\n"
        f"SELECT COUNT(*) AS source_row_count FROM {schema}.{table};"
    )


def _row_count_sql_sf(database: str, schema: str, table: str) -> str:
    full = f"{database}.{schema}.{table}" if database else f"{schema}.{table}"
    return (
        f"-- ── ROW COUNT: Snowflake ────────────────────────────────────────\n"
        f"SELECT COUNT(*) AS target_row_count FROM {full};"
    )


def _null_check_sql_pg(schema: str, table: str, mappings: List[ColumnMapping]) -> str:
    """Generate NULL % per column query for PostgreSQL."""
    if not mappings:
        return ""
    total = len(mappings)
    null_counts = ",\n    ".join(
        f"ROUND(100.0 * SUM(CASE WHEN {cm.source_column} IS NULL THEN 1 ELSE 0 END) / COUNT(*), 2)"
        f" AS {cm.source_column}_null_pct"
        for cm in mappings
    )
    return (
        f"-- ── NULL % CHECK: PostgreSQL ────────────────────────────────────\n"
        f"SELECT\n    COUNT(*) AS total_rows,\n    {null_counts}\n"
        f"FROM {schema}.{table};"
    )


def _null_check_sql_sf(database: str, schema: str, table: str, mappings: List[ColumnMapping]) -> str:
    """Generate NULL % per column query for Snowflake."""
    if not mappings:
        return ""
    full = f"{database}.{schema}.{table}" if database else f"{schema}.{table}"
    null_counts = ",\n    ".join(
        f"ROUND(100.0 * SUM(CASE WHEN {cm.target_column} IS NULL THEN 1 ELSE 0 END) / COUNT(*), 2)"
        f" AS {cm.source_column}_null_pct"
        for cm in mappings
    )
    return (
        f"-- ── NULL % CHECK: Snowflake ─────────────────────────────────────\n"
        f"SELECT\n    COUNT(*) AS total_rows,\n    {null_counts}\n"
        f"FROM {full};"
    )


def _duplicate_pk_sql_sf(database: str, schema: str, table: str, pk_cols: List[str]) -> str:
    """Detect duplicate PKs in Snowflake target."""
    full = f"{database}.{schema}.{table}" if database else f"{schema}.{table}"
    pk_expr = ", ".join(pk_cols)
    return (
        f"-- ── DUPLICATE PK CHECK: Snowflake ──────────────────────────────\n"
        f"-- Expected result: 0 rows (no duplicates)\n"
        f"SELECT {pk_expr}, COUNT(*) AS cnt\n"
        f"FROM {full}\n"
        f"GROUP BY {pk_expr}\n"
        f"HAVING COUNT(*) > 1\n"
        f"ORDER BY cnt DESC;"
    )


def _missing_rows_sql(
    pg_schema: str, pg_table: str,
    sf_db: str, sf_schema: str, sf_table: str,
    pk_cols: List[str],
) -> str:
    """
    Generate a query to find PK values in source that are missing in target.
    NOTE: This query uses a sub-select approach — run the inner queries
    separately and compare, OR use a DB-link / external query tool.
    """
    sf_full = f"{sf_db}.{sf_schema}.{sf_table}" if sf_db else f"{sf_schema}.{sf_table}"
    pk_src = ", ".join(pk_cols)
    pk_tgt = ", ".join(c.upper() for c in pk_cols)
    pk_concat_src = " || '|' || ".join(f"CAST({c} AS TEXT)" for c in pk_cols)
    pk_concat_tgt = " || '|' || ".join(f"CAST({c.upper()} AS VARCHAR)" for c in pk_cols)

    return (
        f"-- ── MISSING ROWS CHECK ─────────────────────────────────────────\n"
        f"-- Step 1: Run on PostgreSQL — get all source PKs\n"
        f"SELECT {pk_src}, {pk_concat_src} AS pk_key\n"
        f"FROM {pg_schema}.{pg_table}\n"
        f"ORDER BY {pk_src};\n\n"
        f"-- Step 2: Run on Snowflake — get all target PKs\n"
        f"SELECT {pk_tgt}, {pk_concat_tgt} AS pk_key\n"
        f"FROM {sf_full}\n"
        f"ORDER BY {pk_tgt};\n\n"
        f"-- Step 3: Compare the pk_key columns — any value in Step 1 missing\n"
        f"-- from Step 2 is a ROW MISSING IN TARGET (data loss during migration)."
    )


