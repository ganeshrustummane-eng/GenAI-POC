class QueryBuilder:
    """
    Connects to source + target, extracts schema, asks AI for rules,
    builds and returns all validation SQL — without executing any of it.
    """

    def __init__(
        self,
        api_key: Optional[str] = None,
        api_base: Optional[str] = None,
        api_version: Optional[str] = None,
        model: Optional[str] = None,
    ):
        self.api_key     = api_key     or os.getenv("DIAL_API_KEY", "")
        self.api_base    = api_base    or os.getenv("DIAL_API_BASE", _DEFAULT_API_BASE)
        self.api_version = api_version or os.getenv("DIAL_API_VERSION", _DEFAULT_API_VERSION)
        self.model       = model       or os.getenv("DIAL_MODEL", _DEFAULT_MODEL)
        self._ai_active  = bool(self.api_key)

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def build(
        self,
        pg_database: str,
        pg_schema: str,
        pg_table: str,
        sf_schema: str,
        sf_table: str,
        sf_database: Optional[str] = None,
        primary_keys: Optional[List[str]] = None,
        save_sql: bool = True,
    ) -> QueryResult:
        """
        Main entry point.

        Args:
            pg_database  : PostgreSQL database name
            pg_schema    : PostgreSQL schema (e.g. 'public')
            pg_table     : Source table name
            sf_schema    : Snowflake schema
            sf_table     : Snowflake table name (UPPER CASE recommended)
            sf_database  : Snowflake database (default: SNOWFLAKE_DATABASE env var)
            primary_keys : PK column names (auto-detected if empty)
            save_sql     : Save generated SQL to validation_sql/ folder

        Returns:
            QueryResult with all generated SQL strings
        """
        _sf_db = sf_database or os.getenv("SNOWFLAKE_DATABASE", "")

        result = QueryResult(
            table_name=pg_table,
            source_db=f"postgresql://{pg_database}.{pg_schema}.{pg_table}",
            target_db=f"snowflake://{_sf_db}.{sf_schema}.{sf_table}",
        )

        # ── Step 1: Extract schemas ──────────────────────────────────────────
        print(f"\n  [1/3] Connecting to databases and extracting schemas...")
        try:
            pg_ext = PostgresSchemaExtractor(database=pg_database)
            sf_ext = SnowflakeSchemaExtractor(database=_sf_db)
            src_cols = pg_ext.extract_columns(pg_schema, pg_table)
            tgt_cols = sf_ext.extract_columns(sf_schema, sf_table)
        except Exception as exc:
            print(f"  ✗ Schema extraction failed: {exc}")
            raise

        # Schema comparison (informational)
        comparison = SchemaComparator.compare(
            source_columns=src_cols,
            target_columns=tgt_cols,
            source_table=f"{pg_schema}.{pg_table}",
            target_table=f"{sf_schema}.{sf_table}",
        )
        comparison.print_summary()

        # Auto-detect PKs if not provided
        pks = primary_keys or []
        if not pks:
            pks = _auto_detect_pks(src_cols)
            if pks:
                print(f"  [PK auto-detected] {pks}")

        # ── Step 2: Get column mappings from AI ──────────────────────────────
        print(f"\n  [2/3] Asking AI to assign transformation rules...")
        src_dicts = [column_info_to_dict(c) for c in src_cols]
        tgt_dicts = [column_info_to_dict(c) for c in tgt_cols]

        mappings, explanation, generated_by = self._get_mappings(
            src_dicts, tgt_dicts,
            pg_schema, pg_table,
            sf_schema, sf_table, _sf_db,
            pks,
        )
        result.column_mappings = mappings
        result.ai_explanation  = explanation
        result.generated_by    = generated_by

        # Collect skipped columns
        result.skipped_columns = [
            cm.source_column for cm in mappings if cm.ignore_validation
        ]

        # ── Step 3: Build all SQL queries ────────────────────────────────────
        print(f"\n  [3/3] Generating validation SQL queries...")
        active_mappings = [cm for cm in mappings if not cm.ignore_validation]
        pk_cols = [cm.source_column for cm in mappings if cm.primary_key]

        result.source_sql = _build_source_sql(pg_schema, pg_table, active_mappings, pk_cols)
        result.target_sql = _build_target_sql(_sf_db, sf_schema, sf_table, active_mappings, pk_cols)

        result.row_count_source_sql = _row_count_sql_pg(pg_schema, pg_table)
        result.row_count_target_sql = _row_count_sql_sf(_sf_db, sf_schema, sf_table)

        result.null_check_source_sql = _null_check_sql_pg(pg_schema, pg_table, active_mappings)
        result.null_check_target_sql = _null_check_sql_sf(_sf_db, sf_schema, sf_table, active_mappings)

        if pk_cols:
            result.duplicate_pk_sql = _duplicate_pk_sql_sf(_sf_db, sf_schema, sf_table, pk_cols)
            result.missing_rows_sql = _missing_rows_sql(
                pg_schema, pg_table,
                _sf_db, sf_schema, sf_table,
                pk_cols
            )

        # ── Save SQL files ───────────────────────────────────────────────────
        if save_sql:
            _save_sql_file(result, pg_table)

        return result

    # ------------------------------------------------------------------
    # AI / static mapping
    # ------------------------------------------------------------------

    def _get_mappings(
        self,
        src_cols: List[Dict], tgt_cols: List[Dict],
        pg_schema: str, pg_table: str,
        sf_schema: str, sf_table: str, sf_db: str,
        pk_hints: List[str],
    ):
        """
        Returns (mappings, explanation, generated_by).
        Tries AI first, falls back to static rule matching.
        """
        # Pair source and target columns by name
        tgt_map = {c["column_name"].upper(): c for c in tgt_cols}
        pairs = []
        for sc in src_cols:
            tc = tgt_map.get(sc["column_name"].upper())
            if tc:
                pairs.append({"source": sc, "target": tc})
            else:
                print(f"  [WARN] No target column for '{sc['column_name']}' — will skip")

        if self._ai_active:
            return self._ai_mappings(pairs, pg_schema, pg_table, sf_schema, sf_table, sf_db, pk_hints)
        else:
            print("  [INFO] No DIAL_API_KEY — using static rule matching.")
            return self._static_mappings(pairs, pk_hints)

    def _ai_mappings(
        self,
        pairs: List[Dict],
        pg_schema: str, pg_table: str,
        sf_schema: str, sf_table: str, sf_db: str,
        pk_hints: List[str],
    ):
        """Call DIAL/GPT-4o to get rule assignments for each column pair."""
        try:
            from openai import AzureOpenAI
        except ImportError:
            print("  [WARN] openai package missing — using static fallback.")
            return self._static_mappings(pairs, pk_hints)

        client = AzureOpenAI(
            api_key=self.api_key,
            api_version=self.api_version,
            azure_endpoint=self.api_base,
        )

        system_prompt = _build_system_prompt()
        user_prompt   = _build_user_prompt(
            pairs, pg_schema, pg_table, sf_schema, sf_table, sf_db, pk_hints
        )

        try:
            response = client.chat.completions.create(
                model=self.model,
                messages=[
                    {"role": "system", "content": system_prompt},
                    {"role": "user",   "content": user_prompt},
                ],
                temperature=0,
                response_format={"type": "json_object"},
                extra_headers={"Api-Key": self.api_key},
            )
            raw = response.choices[0].message.content
            return _parse_ai_response(raw, pairs)
        except Exception as exc:
            print(f"  [WARN] AI call failed ({exc}) — using static fallback.")
            return self._static_mappings(pairs, pk_hints)

    @staticmethod
    def _static_mappings(pairs: List[Dict], pk_hints: List[str]):
        """Rule matching without AI — uses trigger_type_pairs from rule catalog."""
        import re, json as _json
        with open(Path(__file__).parent / "rules_catalog.json", encoding="utf-8") as f:
            catalog = _json.load(f)
        chain_order = catalog.get("chaining_order", [])
        rules_data  = catalog.get("rules", [])

        pk_hints_up = [h.upper() for h in pk_hints]
        mappings = []

        for pair in pairs:
            sc = pair["source"]
            tc = pair["target"]
            src_base = re.sub(r"\(.*\)", "", sc["data_type"]).strip().upper()
            tgt_base = re.sub(r"\(.*\)", "", tc["data_type"]).strip().upper()

            matched_rules = []
            for rule in rules_data:
                if not rule.get("auto_detect"):
                    continue
                for tp in rule["trigger_type_pairs"]:
                    s, t = tp["source"].upper(), tp["target"].upper()
                    if (s == "*" or src_base.startswith(s)) and (t == "*" or tgt_base.startswith(t)):
                        rt = _enum_val_to_rule_type(rule["enum_value"])
                        if rt and rt not in matched_rules:
                            matched_rules.append(rt)
                        break

            matched_rules.sort(
                key=lambda r: chain_order.index(r.value) if r.value in chain_order else 999
            )

            mappings.append(ColumnMapping(
                source_column=sc["column_name"],
                target_column=tc["column_name"],
                source_data_type=sc["data_type"],
                target_data_type=tc["data_type"],
                apply_rules=matched_rules,
                primary_key=sc["column_name"].upper() in pk_hints_up,
            ))

        return (
            mappings,
            "Rules assigned by static type-pair matching. Set DIAL_API_KEY to enable AI.",
            "static",
        )


