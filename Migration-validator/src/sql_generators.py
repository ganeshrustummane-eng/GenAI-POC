"""
SQL Query Generators for Different Database Types
Generates SQL queries for data validation
"""

from typing import List, Optional, Dict
from models import DatabaseType, ColumnMapping, TransformationRuleType
from transformation_rules import rules_engine


class BaseSQLGenerator:
    """Base class for SQL generators"""
    
    def __init__(self, db_type: DatabaseType):
        self.db_type = db_type
    
    def generate_row_count_query(self, schema: str, table: str) -> str:
        """Generate query to get row count"""
        raise NotImplementedError
    
    def generate_data_query(
        self,
        schema: str,
        table: str,
        column_mappings: List[ColumnMapping]
    ) -> str:
        """Generate query to fetch and transform data"""
        raise NotImplementedError
    
    def generate_comparison_query(
        self,
        source_schema: str,
        source_table: str,
        target_schema: str,
        target_table: str,
        column_mappings: List[ColumnMapping]
    ) -> tuple:
        """Generate both source and target queries for comparison"""
        raise NotImplementedError


class MSSQLGenerator(BaseSQLGenerator):
    """SQL Server query generator"""
    
    def __init__(self):
        super().__init__(DatabaseType.MSSQL)
    
    def generate_row_count_query(self, schema: str, table: str) -> str:
        """Generate MS SQL row count query"""
        return f"""
        SELECT 
            COUNT(*) as row_count,
            '{table}' as table_name,
            GETDATE() as query_time
        FROM [{schema}].[{table}]
        """
    
    def generate_data_query(
        self,
        schema: str,
        table: str,
        column_mappings: List[ColumnMapping]
    ) -> str:
        """Generate MS SQL data query with transformations"""
        
        # Build SELECT clause with transformations
        select_clauses = []
        pk_columns = []
        
        for mapping in column_mappings:
            col = mapping.source_column
            
            if mapping.apply_rules:
                # Apply transformation rules
                expr = rules_engine.apply_rules(col, mapping.apply_rules, self.db_type)
                select_clauses.append(expr)
            else:
                select_clauses.append(f"{col} AS {col}_normalized")
            
            if mapping.primary_key:
                pk_columns.append(col)
        
        select_sql = ",\n            ".join(select_clauses)
        
        # Add row number for detailed comparison
        if pk_columns:
            pk_order = ", ".join(pk_columns)
        else:
            pk_order = "1"
        
        return f"""
        SELECT 
            {select_sql},
            ROW_NUMBER() OVER (ORDER BY {pk_order}) as rn,
            GETDATE() as extracted_at
        FROM [{schema}].[{table}]
        ORDER BY {pk_order}
        """
    
    def generate_comparison_query(
        self,
        source_schema: str,
        source_table: str,
        target_schema: str,
        target_table: str,
        column_mappings: List[ColumnMapping]
    ) -> tuple:
        """Generate source and target comparison queries"""
        
        source_query = self.generate_data_query(source_schema, source_table, column_mappings)
        
        return (source_query, None)  # Target will be generated by SnowflakeGenerator


