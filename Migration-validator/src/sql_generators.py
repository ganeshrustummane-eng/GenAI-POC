class QueryGenerator:
    """Factory for generating SQL queries"""
    
    def __init__(self):
        self.generators: Dict[DatabaseType, BaseSQLGenerator] = {
            DatabaseType.MSSQL: MSSQLGenerator(),
            DatabaseType.POSTGRESQL: PostgreSQLGenerator(),
            DatabaseType.SNOWFLAKE: SnowflakeGenerator(),
        }
    
    def get_generator(self, db_type: DatabaseType) -> BaseSQLGenerator:
        """Get generator for database type"""
        return self.generators.get(db_type)
    
    def generate_validation_queries(
        self,
        source_type: DatabaseType,
        source_schema: str,
        source_table: str,
        source_database: Optional[str] = None,
        target_type: DatabaseType = DatabaseType.SNOWFLAKE,
        target_database: Optional[str] = None,
        target_schema: Optional[str] = None,
        target_table: Optional[str] = None,
        column_mappings: Optional[List[ColumnMapping]] = None
    ) -> Dict[str, str]:
        """
        Generate complete validation queries
        
        Returns:
            Dictionary with 'source_row_count', 'target_row_count', 'source_data', 'target_data' queries
        """
        
        if not column_mappings:
            column_mappings = []
        
        source_gen = self.get_generator(source_type)
        target_gen = self.get_generator(target_type)
        
        queries = {}
        
        # Row count queries
        if source_type == DatabaseType.MSSQL:
            queries['source_row_count'] = source_gen.generate_row_count_query(source_schema, source_table)
        elif source_type == DatabaseType.POSTGRESQL:
            queries['source_row_count'] = source_gen.generate_row_count_query(source_schema, source_table)
        
        if target_type == DatabaseType.SNOWFLAKE:
            queries['target_row_count'] = target_gen.generate_row_count_query(
                target_database, target_schema, target_table
            )
        
        # Data queries
        if source_type == DatabaseType.MSSQL:
            queries['source_data'] = source_gen.generate_data_query(
                source_schema, source_table, column_mappings
            )
        elif source_type == DatabaseType.POSTGRESQL:
            queries['source_data'] = source_gen.generate_data_query(
                source_schema, source_table, column_mappings
            )
        
        if target_type == DatabaseType.SNOWFLAKE:
            queries['target_data'] = target_gen.generate_data_query(
                target_database, target_schema, target_table, column_mappings
            )
        
        return queries


# Create singleton instance
query_generator = QueryGenerator()
